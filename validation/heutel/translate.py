from pathlib import Path
import re, hashlib, json
root=Path(__file__).resolve().parents[2]
src=root/'validation/heutel/original'
# Translate only scalar algebra/structural coefficients; never execute source text.
def logical(path):
    s=re.sub(r'%\{.*?%\}', '', path.read_text(), flags=re.S); s='\n'.join(x.split('%')[0] for x in s.splitlines())
    return re.sub(r'\.\.\.\s*\n\s*','',s)
def expr(s):
    return re.sub(r'\blambda\b','lam',s.strip().replace('^','**'))
def assignments(s):
    lines=[]
    for statement in s.split(';'):
        statement=statement.strip()
        if not statement: continue
        if '=' not in statement: raise ValueError(statement)
        left,right=statement.split('=',1); left=left.strip(); right=right.strip()
        if left.startswith('h('):
            idx=left[2:-1].split(',')
            def index(v):
                if v==':': return ':'
                if ':' in v:
                    a,b=v.split(':'); return f'{int(a)-1}:{int(b)}'
                return str(int(v)-1)
            left='h['+', '.join(index(v) for v in idx)+']'
            if right.startswith('zeros('): right='0.0'
        left=re.sub(r'X\((\d+)\)',lambda m:f'X[{int(m[1])-1}]',left)
        lines.append('    '+expr(left)+' = '+expr(right))
    return lines
params=['beta','delta','rho','alpha','eta','theta1','theta2','gamma','phic','d2','d1','d0','erowcoef']
header='''"""Scalar algebra ported from Garth Heutel's MATLAB replication files (2011).

Generated by validation/heutel/translate.py; equations retain source order.
See docs/heutel.md for provenance, calibration differences and limitations.
"""\nimport numpy as np\n\n'''
out=header
for name,source,dim in [('planner_ss','steadystate.m',3),('tax_ss','steadystate_tax.m',2)]:
    s=logical(src/source); s=s[s.index('k = guess(1)'):]
    s=re.sub(r'guess\((\d+)\)',lambda m:f'guess[{int(m[1])-1}]',s)
    out+=f'def {name}(guess, p):\n'
    for p in params: out+=f'    {p} = p.{p}\n'
    out+=f'    X = np.zeros({dim})\n'+'\n'.join(assignments(s))+'\n    return X\n\n'
# Levels/derivatives/multipliers are shared across all tax variants.
s=logical(src/'SolveSystem_tax.m'); start=s.index('i_ss = delta*k_ss'); end=s.index('neq = 14')
out+='def tax_levels(k_ss, e_ss, p):\n'
for p in params: out+=f'    {p} = p.{p}\n'
out+='\n'.join(assignments(s[start:end]))+'\n    return {k[:-3]: v for k, v in locals().items() if k.endswith("_ss")}\n\n'
for name,source in [('planner_matrix','SolveSystem.m'),('tax_matrix','SolveSystem_tax.m')]:
    s=logical(src/source); start=s.index('h(1,'); end=s.index('condn =')
    out+=f'def {name}(ss, p):\n'
    for p in params: out+=f'    {p} = p.{p}\n'
    keys=['c','e','k','x','mu','y','z','i','a']+([] if name.startswith('planner') else ['tau','r','lambda','zeta','omega'])
    for k in keys: out+=f'    {k}_ss = ss["{k}"]\n'
    out+=f'    h = np.zeros(({len(keys)}, {len(keys)*3}))\n'
    out+='\n'.join(assignments(s[start:end]))+'\n    return h\n\n'
s=logical(src/'SolveSystem_quota_AsymInfo.m'); start=s.index('h(9,:)'); end=s.index('[b,rts',start)
out+='def quota_firm_rows(h, ss, p):\n'
for p in params: out+=f'    {p} = p.{p}\n'
for k in ['y','k','mu','r']: out+=f'    {k}_ss = ss["{k}"]\n'
out+='\n'.join(assignments(s[start:end]))+'\n    return h\n'
(root/'src/dsgekit/examples/_heutel_algebra.py').write_text(out)
manifest={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(src.iterdir())}
(root/'validation/heutel/source-sha256.json').write_text(json.dumps(manifest,indent=2)+'\n')
