"""Make the Rep-MMB MATLAB inputs explicit in inspectable .mod working copies.

The downloaded sources stay unchanged. Only the known scalar-assignment ranges of the ToTEM and
GEAR helpers are copied; any other MATLAB statement in those ranges is an error. GNSS's text
vector and AINO's MAT file are read as data. No MATLAB code is executed and no numeric calibration
is stored in this script. QUEST3's reference starting point is computed independently with dsgelab
and written as an explicit initval. Outputs go to out/prepared/, next to the Dynare exports.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import numpy as np
from scipy.io import loadmat

HERE = Path(__file__).resolve().parent
SOURCES = {
    "CA_ToTEM10": ("CA_ToTEM10_rep_steadystate.m",),
    "DEREA_GEAR16": ("set_params_31_08_aw1.m", "set_steadystate_31_08_aw1.m",
                     "DEREA_GEAR16_rep_steadystate.m"),
    "EA_GNSS10": ("median_values.txt",),
    "FI_AINO16": ("all_parameters_February2016.mat",),
}


def _assignments(path: Path, start: str, end: str) -> str:
    text = path.read_text()
    try:
        chunk = text[text.index(start):text.index(end, text.index(start))]
    except ValueError as exc:
        raise ValueError(f"{path}: assignment range not found") from exc
    out = []
    for line in chunk.splitlines():
        line = re.split(r"%|//", line, maxsplit=1)[0].strip()
        if not line:
            continue
        match = re.fullmatch(r"([A-Za-z_]\w*)\s*=\s*(.+?)\s*;", line)
        if match is None:
            raise ValueError(f"{path}: unsupported MATLAB in assignment range: {line}")
        out.append(f"{match.group(1)} = {match.group(2)};")
    if not out:
        raise ValueError(f"{path}: empty assignment range")
    return "\n".join(out)


def _header(name: str) -> str:
    files = ", ".join(SOURCES[name])
    return f"// Generated by prepare.py from the pinned Rep-MMB inputs: {files}.\n"


def _totem(mods: Path) -> str:
    text = (mods / "CA_ToTEM10.mod").read_text()
    values = _assignments(mods / "CA_ToTEM10_rep_steadystate.m",
                          "cbal =", "%CA_ToTEM10_set_auxiliary_variables")
    block = f"\nsteady_state_model;\n{values}\nend;\n"
    return _header("CA_ToTEM10") + text.replace("\n//Shocks", block + "\n//Shocks", 1)


def _gear(mods: Path) -> str:
    text = (mods / "DEREA_GEAR16.mod").read_text()
    calibration = _assignments(mods / "set_params_31_08_aw1.m", "mu_a =",
                               "%%%%%%%%%%%%%%%%%%%%%%")
    calibration += "\n" + _assignments(mods / "set_steadystate_31_08_aw1.m", "pr_ts    =",
                                       "\n NumberOfParameters = M_.param_nbr;")
    values = _assignments(mods / "DEREA_GEAR16_rep_steadystate.m", "i_a_t   = i_a_ts;",
                          "  endoList =")
    text = text.replace("set_params_31_08_aw1;", calibration, 1)
    block = f"\nsteady_state_model;\n{values}\nend;\n"
    return _header("DEREA_GEAR16") + text.replace("\nresid;", block + "\nresid;", 1)


def _gnss(mods: Path) -> str:
    text = (mods / "EA_GNSS10.mod").read_text()
    values = np.loadtxt(mods / "median_values.txt", ndmin=1)
    if values.size != 25:
        raise ValueError(f"{mods / 'median_values.txt'}: expected 25 values, got {values.size}")
    text = text.replace("load median_values.txt;\ncoeffs = median_values;", "", 1)
    text = re.sub(r"coeffs\((\d+)\)",
                  lambda m: format(float(values[int(m.group(1)) - 1]), ".17g"), text)
    if "coeffs" in text or "median_values" in text:
        raise ValueError("EA_GNSS10: unexpanded median_values reference")
    text = text.replace("mean([eps_bh,eps_be])", "(eps_bh+eps_be)/2", 1)
    return _header("EA_GNSS10") + text


def _aino(mods: Path) -> str:
    text = (mods / "FI_AINO16.mod").read_text()
    data = loadmat(mods / "all_parameters_February2016.mat", squeeze_me=True,
                   struct_as_record=False)
    declaration = re.search(r"^\s*parameters\b(.*?);", text, flags=re.S | re.M)
    if declaration is None:
        raise ValueError("FI_AINO16: parameter declaration not found")
    names = re.findall(r"[A-Za-z_]\w*", re.sub(r"%.*|//.*", " ", declaration.group(1)))
    shock_values = re.findall(r"(seeps\w+)\s*=\s*pp\.(seeps\w+)\s*;", text)
    missing = [name for name in names if name not in data]
    missing += [field for _, field in shock_values if field not in data]
    if missing:
        raise ValueError(f"FI_AINO16: missing in MAT file: {sorted(set(missing))}")
    assignments = [f"{name} = {float(data[name]):.17g};" for name in names]
    assignments += [f"{name} = {float(data[field]):.17g};" for name, field in shock_values]
    start = text.index("load all_parameters_February2016;")
    end = text.index("model(linear);", start)
    text = text[:start] + "\n".join(assignments) + "\n\n" + text[end:]
    return _header("FI_AINO16") + text


def prepare_quest_start(mods: Path = HERE / "mods") -> str:
    from dsgelab.dynare import from_mod

    mf = from_mod(Path(mods) / "EA_QUEST3.mod")
    steady = mf.steady_state(tol=1e-12)
    values = "\n".join(f"{name} = {steady.values[name]:.17g};" for name in mf.endogenous)
    text = (Path(mods) / "EA_QUEST3.mod").read_text()
    text, count = re.subn(r"initval\s*;.*?end\s*;", f"initval;\n{values}\nend;", text,
                          count=1, flags=re.S)
    if count != 1:
        raise ValueError("EA_QUEST3: initval block not found")
    return ("// Dynare reference start independently computed by dsgelab; Dynare checks its residual.\n"
            + text)


_BUILDERS = {"CA_ToTEM10": _totem, "DEREA_GEAR16": _gear,
             "EA_GNSS10": _gnss, "FI_AINO16": _aino}


def prepare_text(name: str, mods: Path = HERE / "mods") -> str:
    if name not in _BUILDERS:
        raise ValueError(f"{name}: no external MATLAB inputs to prepare")
    return _BUILDERS[name](Path(mods))


def main(names: list[str]) -> int:
    out = HERE / "out" / "prepared"
    out.mkdir(parents=True, exist_ok=True)
    for name in names or [*list(_BUILDERS), "EA_QUEST3"]:
        if name == "EA_QUEST3":
            dst = out / "EA_QUEST3_dynare_start.mod"
            text = prepare_quest_start()
        else:
            dst = out / f"{name}.mod"
            text = prepare_text(name)
        dst.write_text(text)
        print(dst)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
